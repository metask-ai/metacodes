//! Versioned evaluation-event projection for harness experiments.
//!
//! CoreEvent is the internal UI/runtime protocol and may evolve with the app.
//! EvalEvent is a deliberately smaller, stable measurement protocol. This
//! backend projects semantic CoreEvents into NDJSON envelopes without storing
//! raw tool inputs or results: only sizes, SHA-256 digests, timing and error
//! categories leave the process. Use TeeBackend to attach it to a normal UI.

const std = @import("std");
const pfs = @import("platform").fs;
const ui_backend = @import("protocol/ui_backend.zig");
const util_json = @import("../util/json.zig");
const util_time = @import("../util/time.zig");
const pricing = @import("../util/pricing.zig");
const log = @import("../util/log.zig");
const AbortSignal = @import("../util/abort.zig").AbortSignal;
const request_gate = @import("request_gate.zig");
const ToolExecutionPolicy = @import("../tools/context.zig").ToolExecutionPolicy;

const CoreEvent = ui_backend.CoreEvent;
const UiEvent = ui_backend.UiEvent;
const UiBackend = ui_backend.UiBackend;
const SessionId = ui_backend.SessionId;

pub const SCHEMA_VERSION: u32 = 3;
pub const MAX_ARTIFACT_BYTES: usize = 64 * 1024 * 1024;

/// Frozen before a rollout starts. Unknown values stay explicit; callers must
/// never claim `recorded_at_execution` for values inferred after the run.
pub const RunMetadata = struct {
    run_id: []const u8 = "unknown",
    invocation: u32 = 0,
    trial: u32 = 0,
    suite_id: ?[]const u8 = null,
    task_id: ?[]const u8 = null,
    task_fingerprint: ?[]const u8 = null,
    task_fingerprint_provenance: []const u8 = "unknown",
    model_provider: []const u8 = "unknown",
    model_id: []const u8 = "unknown",
    model_fingerprint: ?[]const u8 = null,
    runtime_model_provider: []const u8 = "unknown",
    runtime_model_id: []const u8 = "unknown",
    harness_config_id: []const u8 = "unknown",
    harness_revision: []const u8 = "unknown",
    harness_fingerprint: ?[]const u8 = null,
    permission_mode: []const u8 = "unknown",
    runtime_permission_mode: []const u8 = "unknown",
    environment_fingerprint: ?[]const u8 = null,
    grader_fingerprint: ?[]const u8 = null,
    max_metered_tokens: ?u64 = null,
    max_cost_usd: ?f64 = null,
};

/// Execution-grounded metadata generated by the evaluation runner before the
/// child process starts. It arrives through METACODES_EVAL_METADATA_FD; the fd
/// is closed before agent tools run and the event fd is marked close-on-exec.
pub const RuntimeMetadataFile = struct {
    schema_version: u32,
    events_path: []const u8,
    run_id: []const u8,
    trial: u32,
    suite_id: []const u8,
    task_id: []const u8,
    task_fingerprint: []const u8,
    model_provider: []const u8,
    model_id: []const u8,
    model_fingerprint: []const u8,
    harness_config_id: []const u8,
    harness_revision: []const u8,
    harness_fingerprint: []const u8,
    permission_mode: []const u8,
    environment_fingerprint: []const u8,
    grader_fingerprint: []const u8,
    /// Optional host-sealed provider-visible/executable tool ceiling. The
    /// production memory runner uses this to remove interactive and nested
    /// provider tools from the model schema, not merely deny them after the
    /// model has already selected one.
    allowed_tools: ?[]const []const u8 = null,
    max_metered_tokens: ?u64 = null,
    max_cost_usd: ?f64 = null,
};

/// Process-wide budget shared by every user submission in one scored rollout.
/// The reserve is a conservative upper bound for one provider request. Once
/// the remaining allowance cannot cover another request, the current run is
/// aborted before the next request boundary and the host exits fail-closed.
pub const EvaluationBudget = struct {
    max_metered_tokens: ?u64 = null,
    max_cost_usd: ?f64 = null,
    used_metered_tokens: u64 = 0,
    used_cost_usd: f64 = 0,
    request_reserve_tokens: u64 = 0,
    request_reserve_cost_usd: f64 = 0,
    abort: ?*AbortSignal = null,

    pub fn configureRequestReserve(
        self: *EvaluationBudget,
        max_input_tokens: u64,
        max_output_tokens: u64,
        model: []const u8,
    ) void {
        self.request_reserve_tokens = max_input_tokens +| max_output_tokens;
        const rates = pricing.rateFor(model);
        const worst_input_rate = @max(
            rates.input_per_mtok,
            @max(rates.cache_read_per_mtok, rates.cache_write_per_mtok),
        );
        self.request_reserve_cost_usd =
            @as(f64, @floatFromInt(max_input_tokens)) / 1_000_000.0 * worst_input_rate +
            @as(f64, @floatFromInt(max_output_tokens)) / 1_000_000.0 * rates.output_per_mtok;
    }

    pub fn allowsAnotherRequest(self: *const EvaluationBudget) bool {
        if (self.max_metered_tokens == null and self.max_cost_usd == null) return true;
        if (self.request_reserve_tokens == 0 or
            !std.math.isFinite(self.request_reserve_cost_usd) or
            self.request_reserve_cost_usd <= 0)
            return false;
        if (self.max_metered_tokens) |limit| {
            if (self.used_metered_tokens >= limit or
                self.request_reserve_tokens > limit - self.used_metered_tokens)
                return false;
        }
        if (self.max_cost_usd) |limit| {
            if (self.used_cost_usd >= limit or
                self.request_reserve_cost_usd > limit - self.used_cost_usd)
                return false;
        }
        return true;
    }

    fn record(
        self: *EvaluationBudget,
        input_tokens: u64,
        output_tokens: u64,
        cache_read_tokens: u64,
        cache_write_tokens: u64,
        cost_usd: f64,
    ) void {
        self.used_metered_tokens +|= input_tokens;
        self.used_metered_tokens +|= output_tokens;
        self.used_metered_tokens +|= cache_read_tokens;
        self.used_metered_tokens +|= cache_write_tokens;
        self.used_cost_usd += cost_usd;
    }

    fn requestAllowed(raw: *anyopaque) bool {
        const self: *EvaluationBudget = @ptrCast(@alignCast(raw));
        if (self.allowsAnotherRequest()) return true;
        if (self.abort) |signal| signal.abort(.evaluation_budget);
        return false;
    }

    pub fn gate(self: *EvaluationBudget, abort: *AbortSignal) request_gate.Gate {
        self.abort = abort;
        return .{ .ctx = @ptrCast(self), .allows_fn = requestAllowed };
    }
};

pub const RuntimeConfig = struct {
    allocator: std.mem.Allocator,
    parsed: std.json.Parsed(RuntimeMetadataFile),
    invocation: u32 = 0,
    events_fd: ?pfs.Fd = null,
    budget: EvaluationBudget = .{},

    pub fn fromEnvironment(allocator: std.mem.Allocator) !?RuntimeConfig {
        const raw_fd = std.c.getenv("METACODES_EVAL_METADATA_FD") orelse {
            // A path-based evaluation channel can be replaced by the agent it
            // is measuring. Refuse the legacy env instead of producing evidence
            // that looks execution-grounded but is forgeable from a tool call.
            if (std.c.getenv("METACODES_EVAL_METADATA") != null)
                return error.InsecureEvaluationMetadataChannel;
            return null;
        };
        const metadata_fd = try parseInheritedFd(std.mem.span(raw_fd));
        try pfs.makeCloseOnExec(metadata_fd);
        defer pfs.close(metadata_fd);
        const bytes = try readFdAlloc(allocator, metadata_fd, 1024 * 1024);
        defer allocator.free(bytes);
        var config = try fromBytes(allocator, bytes);
        errdefer config.deinit();

        const raw_events_fd = std.c.getenv("METACODES_EVAL_FD") orelse
            return error.MissingEvaluationArtifactFd;
        const events_fd = try parseInheritedFd(std.mem.span(raw_events_fd));
        errdefer pfs.close(events_fd);
        if (events_fd == metadata_fd) return error.InvalidEvaluationArtifactFd;
        try pfs.makeCloseOnExec(events_fd);
        const info = pfs.fileInfo(events_fd) catch return error.InvalidEvaluationArtifactFd;
        if (!info.is_regular or info.size != 0) return error.InvalidEvaluationArtifactFd;
        config.events_fd = events_fd;
        return config;
    }

    pub fn fromFile(allocator: std.mem.Allocator, path: []const u8) !RuntimeConfig {
        const bytes = try readFileAlloc(allocator, path, 1024 * 1024);
        defer allocator.free(bytes);
        return fromBytes(allocator, bytes);
    }

    fn fromBytes(allocator: std.mem.Allocator, bytes: []const u8) !RuntimeConfig {
        // RuntimeConfig outlives `bytes`; force every string into Parsed's
        // arena instead of allowing zero-copy slices into the soon-freed file.
        var parsed = try std.json.parseFromSlice(RuntimeMetadataFile, allocator, bytes, .{
            .ignore_unknown_fields = false,
            .allocate = .alloc_always,
        });
        errdefer parsed.deinit();
        if (parsed.value.schema_version != SCHEMA_VERSION) return error.UnsupportedEvaluationSchema;
        if (parsed.value.events_path.len == 0 or parsed.value.run_id.len == 0 or
            parsed.value.task_fingerprint.len == 0 or parsed.value.model_fingerprint.len == 0 or
            parsed.value.harness_fingerprint.len == 0 or parsed.value.grader_fingerprint.len == 0)
        {
            return error.IncompleteEvaluationMetadata;
        }
        const max_tokens = parsed.value.max_metered_tokens;
        const max_cost = parsed.value.max_cost_usd;
        if ((max_tokens == null) != (max_cost == null))
            return error.IncompleteEvaluationBudget;
        if (max_tokens) |value| if (value == 0) return error.InvalidEvaluationBudget;
        if (max_cost) |value| {
            if (!std.math.isFinite(value) or value <= 0)
                return error.InvalidEvaluationBudget;
        }
        if (parsed.value.allowed_tools) |allowed_tools| {
            if (allowed_tools.len == 0 or allowed_tools.len > 128)
                return error.InvalidEvaluationToolPolicy;
            for (allowed_tools, 0..) |name, index| {
                if (name.len == 0 or name.len > 128)
                    return error.InvalidEvaluationToolPolicy;
                for (allowed_tools[0..index]) |previous| {
                    if (std.mem.eql(u8, name, previous))
                        return error.InvalidEvaluationToolPolicy;
                }
            }
        }
        return .{
            .allocator = allocator,
            .parsed = parsed,
            .budget = .{
                .max_metered_tokens = max_tokens,
                .max_cost_usd = max_cost,
            },
        };
    }

    pub fn toolExecutionPolicy(self: *const RuntimeConfig) ?ToolExecutionPolicy {
        if (self.parsed.value.allowed_tools == null) return null;
        return .{
            .ctx = @ptrCast(self),
            .allowsToolFn = allowsEvaluationTool,
            .allowsInvocationFn = allowsEvaluationInvocation,
        };
    }

    fn allowsEvaluationTool(raw: *const anyopaque, name: []const u8) bool {
        const self: *const RuntimeConfig = @ptrCast(@alignCast(raw));
        const allowed_tools = self.parsed.value.allowed_tools orelse return true;
        for (allowed_tools) |allowed| {
            if (std.mem.eql(u8, name, allowed)) return true;
        }
        return false;
    }

    fn allowsEvaluationInvocation(
        raw: *const anyopaque,
        name: []const u8,
        _: []const u8,
    ) bool {
        return allowsEvaluationTool(raw, name);
    }

    pub fn deinit(self: *RuntimeConfig) void {
        if (self.events_fd) |fd| pfs.close(fd);
        self.events_fd = null;
        self.parsed.deinit();
    }

    pub fn nextMetadata(
        self: *RuntimeConfig,
        runtime_model_provider: []const u8,
        runtime_model_id: []const u8,
        runtime_permission_mode: []const u8,
    ) RunMetadata {
        const f = self.parsed.value;
        const current = self.invocation;
        self.invocation +|= 1;
        return .{
            .run_id = f.run_id,
            .invocation = current,
            .trial = f.trial,
            .suite_id = f.suite_id,
            .task_id = f.task_id,
            .task_fingerprint = f.task_fingerprint,
            .task_fingerprint_provenance = "recorded_at_execution",
            .model_provider = f.model_provider,
            .model_id = f.model_id,
            .model_fingerprint = f.model_fingerprint,
            .runtime_model_provider = runtime_model_provider,
            .runtime_model_id = runtime_model_id,
            .harness_config_id = f.harness_config_id,
            .harness_revision = f.harness_revision,
            .harness_fingerprint = f.harness_fingerprint,
            .permission_mode = f.permission_mode,
            .runtime_permission_mode = runtime_permission_mode,
            .environment_fingerprint = f.environment_fingerprint,
            .grader_fingerprint = f.grader_fingerprint,
            .max_metered_tokens = f.max_metered_tokens,
            .max_cost_usd = f.max_cost_usd,
        };
    }

    pub fn eventsPath(self: *const RuntimeConfig) []const u8 {
        return self.parsed.value.events_path;
    }

    pub fn appendEvaluation(self: *const RuntimeConfig, evaluation: *EvaluationBackend) !void {
        const fd = self.events_fd orelse return error.MissingEvaluationArtifactFd;
        try evaluation.appendToFd(fd);
    }

    pub fn initEvaluation(
        self: *RuntimeConfig,
        allocator: std.mem.Allocator,
        metadata: RunMetadata,
    ) !EvaluationBackend {
        const fd = self.events_fd orelse return error.MissingEvaluationArtifactFd;
        var evaluation = EvaluationBackend.initStreaming(allocator, metadata, fd);
        evaluation.budget = &self.budget;
        return evaluation;
    }

    pub fn configureBudgetReserve(
        self: *RuntimeConfig,
        max_input_tokens: u64,
        max_output_tokens: u64,
        model: []const u8,
    ) void {
        self.budget.configureRequestReserve(max_input_tokens, max_output_tokens, model);
    }

    pub fn requestGate(
        self: *RuntimeConfig,
        abort: *AbortSignal,
    ) request_gate.Gate {
        return self.budget.gate(abort);
    }
};

/// Stable public measurement events. Payload slices are borrowed only for the
/// synchronous stringify call inside EvaluationBackend.emitThunk.
pub const EvalEvent = union(enum) {
    run_started: struct { trace_id: []const u8, metadata: RunMetadata },
    scoped_recall: struct {
        trace_id: []const u8,
        schema_version: []const u8,
        status: []const u8,
        query_sha256: []const u8,
        result_count: usize,
        injected_count: usize,
        injected_bytes: usize,
        injection_sha256: []const u8,
    },
    turn_started: struct { trace_id: []const u8, depth: u8, turn: u32 },
    turn_finished: struct { trace_id: []const u8, depth: u8, turn: u32, tool_calls: u32 },
    model_request_finished: struct { trace_id: []const u8, depth: u8, turn: u32, attempt: u32, elapsed_ms: u64, outcome: []const u8 },
    compact_request_finished: struct { trace_id: []const u8, depth: u8, turn: u32, elapsed_ms: u64, outcome: []const u8, cause: []const u8 },
    tool_stage_finished: struct { trace_id: []const u8, depth: u8, turn: u32, tool_calls: u32, elapsed_ms: u64 },
    tool_started: struct {
        trace_id: []const u8,
        id: []const u8,
        name: []const u8,
        input_bytes: usize,
        input_sha256: []const u8,
    },
    tool_finished: struct {
        trace_id: []const u8,
        id: []const u8,
        name: []const u8,
        is_error: bool,
        error_code: ?[]const u8,
        error_category: ?[]const u8,
        recoverable: ?bool,
        elapsed_ms: u64,
        result_bytes: usize,
        result_sha256: []const u8,
    },
    usage: struct {
        trace_id: []const u8,
        input_tokens: u64,
        output_tokens: u64,
        cache_read_tokens: u64,
        cache_write_tokens: u64,
        estimated_cost_usd: f64,
        pricing_provenance: []const u8,
    },
    policy_decision: struct {
        trace_id: []const u8,
        depth: u8,
        id: []const u8,
        tool: []const u8,
        decision: []const u8,
        source: []const u8,
        allowed: bool,
    },
    retry: struct { trace_id: []const u8, attempt: u32, max: u32, delay_ms: u64 },
    breaker_tripped: struct { trace_id: []const u8, depth: u8, same_err_count: u32 },
    cache_break: struct { trace_id: []const u8, depth: u8, cache_read: u64, cache_creation: u64 },
    continuation: struct { trace_id: []const u8, depth: u8, n: u32, max: u32 },
    auto_compact: struct {
        trace_id: []const u8,
        dropped: u32,
        kept: u32,
        before_tokens: u64,
        after_tokens: u64,
        cause: []const u8,
    },
    run_finished: struct {
        trace_id: []const u8,
        depth: u8,
        turns: u32,
        tool_calls: u32,
        stop_reason: []const u8,
        wall_time_ms: u64,
        dropped_events: u64,
    },
};

