pub const EvaluationBackend = struct {
    allocator: std.mem.Allocator,
    metadata: RunMetadata,
    lines: std.ArrayList(u8) = .empty,
    sequence: u64 = 0,
    started_ns: i128,
    trace_id: [12]u8 = .{0} ** 12,
    has_trace_id: bool = false,
    run_started: bool = false,
    dropped_events: u64 = 0,
    sink_fd: ?pfs.Fd = null,
    flushed_len: usize = 0,
    budget: ?*EvaluationBudget = null,
    pending_scoped_recall: ?ScopedRecallEvidence = null,
    scoped_recall_emitted: bool = false,

    pub fn init(allocator: std.mem.Allocator, metadata: RunMetadata) EvaluationBackend {
        return .{
            .allocator = allocator,
            .metadata = metadata,
            .started_ns = util_time.nowNs(),
        };
    }

    pub fn initStreaming(
        allocator: std.mem.Allocator,
        metadata: RunMetadata,
        sink_fd: pfs.Fd,
    ) EvaluationBackend {
        var out = init(allocator, metadata);
        out.sink_fd = sink_fd;
        return out;
    }

    pub fn deinit(self: *EvaluationBackend) void {
        self.lines.deinit(self.allocator);
    }

    pub fn backend(self: *EvaluationBackend) UiBackend {
        return .{ .ctx = @ptrCast(self), .emit = emitThunk, .poll = pollThunk };
    }

    /// Queue a host recall receipt before agent_loop starts. The receipt is
    /// emitted immediately after run_started, once the loop supplies the real
    /// trace id. Calling this twice would make activation ambiguous, so it is
    /// deliberately rejected.
    pub fn setScopedRecallEvidence(
        self: *EvaluationBackend,
        evidence: ScopedRecallEvidence,
    ) !void {
        if (self.pending_scoped_recall != null or self.scoped_recall_emitted)
            return error.DuplicateScopedRecallEvidence;
        self.pending_scoped_recall = evidence;
    }

    pub fn jsonl(self: *const EvaluationBackend) []const u8 {
        return self.lines.items;
    }

    /// Append this run to a caller-owned artifact. The parent directory must
    /// already exist; M2 owns E2E artifact layout and readiness checks.
    pub fn appendToPath(self: *EvaluationBackend, path: []const u8) !void {
        var path_buf: [std.fs.max_path_bytes + 1]u8 = undefined;
        if (path.len + 1 > path_buf.len) return error.PathTooLong;
        @memcpy(path_buf[0..path.len], path);
        path_buf[path.len] = 0;
        const fd = pfs.open(
            @ptrCast(&path_buf),
            .{ .ACCMODE = .WRONLY, .CREAT = true, .APPEND = true, .NOFOLLOW = true },
            @as(std.c.mode_t, 0o600),
        );
        if (fd < 0) return error.OpenFailed;
        defer _ = pfs.close(fd);
        try self.appendToFd(fd);
    }

    pub fn appendToFd(self: *EvaluationBackend, fd: pfs.Fd) !void {
        const info = pfs.fileInfo(fd) catch return error.StatFailed;
        if (!info.is_regular) return error.NotRegularFile;
        const same_sink = self.sink_fd != null and self.sink_fd.? == fd;
        const start = if (same_sink) self.flushed_len else 0;
        if (start > self.lines.items.len) return error.InvalidFlushOffset;
        const pending = self.lines.items[start..];
        if (info.size > MAX_ARTIFACT_BYTES or
            pending.len > MAX_ARTIFACT_BYTES - @as(usize, @intCast(info.size)))
            return error.ArtifactTooLarge;
        var offset: usize = 0;
        while (offset < pending.len) {
            const n = pfs.write(fd, pending[offset..]);
            if (n <= 0) return error.WriteFailed;
            offset += @intCast(n);
            // A regular-file write may legally be short. Advance the durable
            // prefix after every successful fragment so retry cannot append
            // duplicate bytes and corrupt the NDJSON stream.
            if (same_sink) self.flushed_len = start + offset;
        }
    }

    fn pollThunk(_: *anyopaque, _: SessionId) ?UiEvent {
        return null;
    }

    fn emitThunk(ctx: *anyopaque, session: SessionId, core_event: CoreEvent) void {
        const self: *EvaluationBackend = @ptrCast(@alignCast(ctx));
        switch (core_event) {
            .diag_turn_begin => |d| {
                self.setTrace(d.trace_id);
                self.ensureRunStarted(session);
                self.append(session, .{ .turn_started = .{
                    .trace_id = self.traceSlice(),
                    .depth = d.depth,
                    .turn = d.turn,
                } });
            },
            .diag_turn_end => |d| {
                self.setTrace(d.trace_id);
                self.ensureRunStarted(session);
                self.append(session, .{ .turn_finished = .{
                    .trace_id = self.traceSlice(),
                    .depth = d.depth,
                    .turn = d.turn,
                    .tool_calls = d.tool_calls,
                } });
            },
            .diag_model_request => |d| {
                self.setTrace(d.trace_id);
                self.ensureRunStarted(session);
                self.append(session, .{ .model_request_finished = .{
                    .trace_id = self.traceSlice(),
                    .depth = d.depth,
                    .turn = d.turn,
                    .attempt = d.attempt,
                    .elapsed_ms = d.elapsed_ms,
                    .outcome = d.outcome,
                } });
            },
            .diag_compact_request => |d| {
                self.setTrace(d.trace_id);
                self.ensureRunStarted(session);
                self.append(session, .{ .compact_request_finished = .{
                    .trace_id = self.traceSlice(),
                    .depth = d.depth,
                    .turn = d.turn,
                    .elapsed_ms = d.elapsed_ms,
                    .outcome = d.outcome,
                    .cause = d.cause,
                } });
            },
            .diag_tool_stage => |d| {
                self.setTrace(d.trace_id);
                self.ensureRunStarted(session);
                self.append(session, .{ .tool_stage_finished = .{
                    .trace_id = self.traceSlice(),
                    .depth = d.depth,
                    .turn = d.turn,
                    .tool_calls = d.tool_calls,
                    .elapsed_ms = d.elapsed_ms,
                } });
            },
            .tool_start => |t| {
                var digest = sha256Hex(t.input);
                self.append(session, .{ .tool_started = .{
                    .trace_id = self.traceSlice(),
                    .id = t.id,
                    .name = t.name,
                    .input_bytes = t.input.len,
                    .input_sha256 = digest[0..],
                } });
            },
            .tool_result => |t| {
                var digest = sha256Hex(t.content);
                self.append(session, .{ .tool_finished = .{
                    .trace_id = self.traceSlice(),
                    .id = t.id,
                    .name = t.name,
                    .is_error = t.is_error,
                    .error_code = if (t.is_error) util_json.extractStringField(t.content, "code") else null,
                    .error_category = if (t.is_error) util_json.extractStringField(t.content, "category") else null,
                    .recoverable = if (t.is_error) util_json.extractBoolField(t.content, "recoverable") else null,
                    .elapsed_ms = t.elapsed_ms,
                    .result_bytes = t.content.len,
                    .result_sha256 = digest[0..],
                } });
            },
            .usage => |u| {
                const estimated_cost_usd = pricing.computeCost(
                    pricing.rateFor(self.metadata.runtime_model_id),
                    u.input_tokens,
                    u.output_tokens,
                    u.cache_read_input_tokens,
                    u.cache_creation_input_tokens,
                );
                self.append(session, .{ .usage = .{
                    .trace_id = self.traceSlice(),
                    .input_tokens = u.input_tokens,
                    .output_tokens = u.output_tokens,
                    .cache_read_tokens = u.cache_read_input_tokens,
                    .cache_write_tokens = u.cache_creation_input_tokens,
                    .estimated_cost_usd = estimated_cost_usd,
                    .pricing_provenance = pricing.provenanceFor(self.metadata.runtime_model_id),
                } });
                // Persist complete usage before the next request boundary can
                // consult the gate and terminate the scored rollout.
                if (self.budget) |budget| budget.record(
                    u.input_tokens,
                    u.output_tokens,
                    u.cache_read_input_tokens,
                    u.cache_creation_input_tokens,
                    estimated_cost_usd,
                );
            },
            .policy_decision => |p| {
                self.setTrace(p.trace_id);
                self.ensureRunStarted(session);
                self.append(session, .{ .policy_decision = .{
                    .trace_id = self.traceSlice(),
                    .depth = p.depth,
                    .id = p.id,
                    .tool = p.tool,
                    .decision = p.decision,
                    .source = p.source,
                    .allowed = p.allowed,
                } });
            },
            .retry_notice => |r| self.append(session, .{ .retry = .{
                .trace_id = self.traceSlice(),
                .attempt = r.attempt,
                .max = r.max,
                .delay_ms = r.delay_ms,
            } }),
            .diag_breaker_tripped => |d| {
                self.setTrace(d.trace_id);
                self.ensureRunStarted(session);
                self.append(session, .{ .breaker_tripped = .{
                    .trace_id = self.traceSlice(),
                    .depth = d.depth,
                    .same_err_count = d.same_err_count,
                } });
            },
            .diag_cache_break => |d| {
                self.setTrace(d.trace_id);
                self.ensureRunStarted(session);
                self.append(session, .{ .cache_break = .{
                    .trace_id = self.traceSlice(),
                    .depth = d.depth,
                    .cache_read = d.cache_read,
                    .cache_creation = d.cache_creation,
                } });
            },
            .diag_continuation => |d| {
                self.setTrace(d.trace_id);
                self.ensureRunStarted(session);
                self.append(session, .{ .continuation = .{
                    .trace_id = self.traceSlice(),
                    .depth = d.depth,
                    .n = d.n,
                    .max = d.max,
                } });
            },
            .auto_compact => |a| self.append(session, .{ .auto_compact = .{
                .trace_id = self.traceSlice(),
                .dropped = a.dropped,
                .kept = a.kept,
                .before_tokens = a.before_tokens,
                .after_tokens = a.after_tokens,
                .cause = a.cause,
            } }),
            .diag_run_end => |d| {
                self.setTrace(d.trace_id);
                self.ensureRunStarted(session);
                self.append(session, .{ .run_finished = .{
                    .trace_id = self.traceSlice(),
                    .depth = d.depth,
                    .turns = d.turns,
                    .tool_calls = d.tool_calls,
                    .stop_reason = d.stop_reason_name,
                    .wall_time_ms = self.elapsedNs() / std.time.ns_per_ms,
                    .dropped_events = self.dropped_events,
                } });
            },
            else => {},
        }
    }

    fn setTrace(self: *EvaluationBackend, trace_id: [12]u8) void {
        self.trace_id = trace_id;
        self.has_trace_id = true;
    }

    fn traceSlice(self: *const EvaluationBackend) []const u8 {
        return if (self.has_trace_id) self.trace_id[0..] else "unknown";
    }

    fn ensureRunStarted(self: *EvaluationBackend, session: SessionId) void {
        if (self.run_started) return;
        self.run_started = true;
        self.append(session, .{ .run_started = .{
            .trace_id = self.traceSlice(),
            .metadata = self.metadata,
        } });
        if (self.pending_scoped_recall) |evidence| {
            self.append(session, .{ .scoped_recall = .{
                .trace_id = self.traceSlice(),
                .schema_version = evidence.schema_version,
                .status = evidence.status,
                .query_sha256 = evidence.query_sha256[0..],
                .result_count = evidence.result_count,
                .injected_count = evidence.injected_count,
                .injected_bytes = evidence.injected_bytes,
                .injection_sha256 = evidence.injection_sha256[0..],
            } });
            self.scoped_recall_emitted = true;
        }
    }

    fn elapsedNs(self: *const EvaluationBackend) u64 {
        const now = util_time.nowNs();
        if (now <= self.started_ns) return 0;
        const delta: u128 = @intCast(now - self.started_ns);
        return @intCast(@min(delta, std.math.maxInt(u64)));
    }

    fn append(self: *EvaluationBackend, session: SessionId, event: EvalEvent) void {
        const envelope = Envelope{
            .sequence = self.sequence,
            .monotonic_elapsed_ns = self.elapsedNs(),
            .session_id = session.asSlice(),
            .event = event,
        };
        const line = std.json.Stringify.valueAlloc(self.allocator, envelope, .{}) catch {
            self.dropped_events += 1;
            log.warn("eval", "dropped evaluation event (serialize OOM)", .{});
            return;
        };
        defer self.allocator.free(line);
        // Reserve the complete NDJSON record first. If allocation fails, do not
        // leave a valid JSON value without its line terminator in the artifact.
        if (line.len + 1 > MAX_ARTIFACT_BYTES -| self.lines.items.len) {
            self.dropped_events +|= 1;
            log.warn("eval", "dropped evaluation event (artifact cap)", .{});
            return;
        }
        self.lines.ensureUnusedCapacity(self.allocator, line.len + 1) catch {
            self.dropped_events += 1;
            log.warn("eval", "dropped evaluation event (buffer OOM)", .{});
            return;
        };
        self.lines.appendSliceAssumeCapacity(line);
        self.lines.appendAssumeCapacity('\n');
        self.sequence += 1;
        if (self.sink_fd) |fd| {
            self.appendToFd(fd) catch |err| {
                // Keep the complete record buffered so the next event or the
                // normal invocation teardown can retry. A hard-killed process
                // may lose only the still-pending suffix; the reader rejects a
                // partial final line fail-closed.
                log.warn("eval", "incremental evaluation event flush failed: {s}", .{@errorName(err)});
            };
        }
    }
};

fn sha256Hex(bytes: []const u8) [64]u8 {
    var digest: [32]u8 = undefined;
    std.crypto.hash.sha2.Sha256.hash(bytes, &digest, .{});
    return std.fmt.bytesToHex(digest, .lower);
}

fn parseInheritedFd(raw: []const u8) !pfs.Fd {
    if (raw.len == 0) return error.InvalidEvaluationFd;
    const value = std.fmt.parseInt(i32, raw, 10) catch return error.InvalidEvaluationFd;
    if (value < 0) return error.InvalidEvaluationFd;
    return @intCast(value);
}

fn readFileAlloc(allocator: std.mem.Allocator, path: []const u8, max_bytes: usize) ![]u8 {
    const path_z = try allocator.dupeZ(u8, path);
    defer allocator.free(path_z);
    const fd = pfs.open(path_z.ptr, .{ .ACCMODE = .RDONLY, .NOFOLLOW = true }, @as(std.c.mode_t, 0));
    if (fd < 0) return error.MetadataNotFound;
    defer _ = pfs.close(fd);
    return readFdAlloc(allocator, fd, max_bytes);
}

fn readFdAlloc(allocator: std.mem.Allocator, fd: pfs.Fd, max_bytes: usize) ![]u8 {
    const info = pfs.fileInfo(fd) catch return error.MetadataStatFailed;
    if (!info.is_regular) return error.MetadataNotRegular;
    if (info.size > max_bytes) return error.MetadataTooLarge;
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(allocator);
    var buf: [4096]u8 = undefined;
    while (true) {
        const n = pfs.read(fd, buf[0..]);
        if (n < 0) return error.MetadataReadFailed;
        if (n == 0) break;
        if (@as(usize, @intCast(n)) > max_bytes -| out.items.len)
            return error.MetadataTooLarge;
        try out.appendSlice(allocator, buf[0..@intCast(n)]);
    }
    return try out.toOwnedSlice(allocator);
}

